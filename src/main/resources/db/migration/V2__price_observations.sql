-- Observations de prix (remplace price_entries) + conversions d'unites.
-- source_type COMMERCIAL (marche) et ADMINISTRATIVE_REFERENCE (reference officielle) ne sont jamais melanges.

alter table materials add column characteristics varchar(255);

insert into measure_units (code, name) values ('barre', 'Barre');

create table unit_conversions (
    id           bigint generated by default as identity primary key,
    from_unit_id bigint not null references measure_units (id),
    to_unit_id   bigint not null references measure_units (id),
    factor       numeric(18, 6) not null check (factor > 0),
    constraint uq_unit_conversions unique (from_unit_id, to_unit_id),
    constraint ck_unit_conversions_distinct check (from_unit_id <> to_unit_id)
);
-- 1 tonne = 1000 kg (fait physique, pas une donnee de marche)
insert into unit_conversions (from_unit_id, to_unit_id, factor)
select f.id, t.id, 1000 from measure_units f, measure_units t where f.code = 't' and t.code = 'kg';

create table price_observations (
    id               bigint generated by default as identity primary key,
    material_id      bigint not null references materials (id),
    supplier_id      bigint references suppliers (id),
    locality         varchar(100) not null,
    sale_unit_id     bigint not null references measure_units (id),
    unit_price       numeric(15, 2) not null check (unit_price >= 0),
    observed_on      date not null,
    source_type      varchar(30) not null check (source_type in ('COMMERCIAL', 'ADMINISTRATIVE_REFERENCE')),
    status           varchar(20) not null check (status in ('PENDING', 'VALIDATED', 'REJECTED')),
    demo             boolean not null default false,
    characteristics  varchar(255),
    source_reference varchar(255),
    created_at       timestamp not null,
    validated_at     timestamp
);
create index idx_price_obs_lookup on price_observations (material_id, source_type, status, observed_on);
create index idx_price_obs_supplier on price_observations (supplier_id);

-- Les anciennes lignes n'ont ni localite ni validation : conservees mais NON validees.
insert into price_observations (material_id, supplier_id, locality, sale_unit_id, unit_price, observed_on,
                                source_type, status, demo, source_reference, created_at)
select p.material_id, p.supplier_id, 'INCONNUE', m.unit_id, p.unit_price, p.valid_from,
       'COMMERCIAL', 'PENDING', false, 'Migre depuis price_entries', p.created_at
from price_entries p join materials m on m.id = p.material_id;

drop table price_entries;
