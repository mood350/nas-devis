-- Schema portable PostgreSQL (aussi execute sur H2 en test). Montants en XOF (FCFA).

create table categories (
    id   bigint generated by default as identity primary key,
    name varchar(100) not null unique
);

create table measure_units (
    id   bigint generated by default as identity primary key,
    code varchar(20) not null unique,
    name varchar(100) not null
);

create table suppliers (
    id      bigint generated by default as identity primary key,
    name    varchar(150) not null unique,
    phone   varchar(50),
    email   varchar(150),
    address varchar(255)
);

create table materials (
    id          bigint generated by default as identity primary key,
    reference   varchar(50) not null unique,
    name        varchar(200) not null,
    category_id bigint not null references categories (id),
    unit_id     bigint not null references measure_units (id),
    active      boolean not null default true
);

-- Historique append-only : le prix courant est la derniere ligne dont valid_from <= date.
create table price_entries (
    id          bigint generated by default as identity primary key,
    material_id bigint not null references materials (id),
    supplier_id bigint references suppliers (id),
    unit_price  numeric(15, 2) not null check (unit_price >= 0),
    valid_from  date not null,
    created_at  timestamp not null
);
create index idx_price_entries_material_from on price_entries (material_id, valid_from);

create table quotes (
    id               bigint generated by default as identity primary key,
    quote_number     varchar(30) unique,
    client_name      varchar(200) not null,
    client_address   varchar(255),
    project_title    varchar(255) not null,
    status           varchar(20) not null,
    issue_date       date not null,
    validity_days    integer not null check (validity_days > 0),
    discount_percent numeric(5, 2) not null check (discount_percent between 0 and 100),
    vat_rate         numeric(5, 2) not null check (vat_rate between 0 and 100),
    subtotal         numeric(15, 2) not null,
    discount_amount  numeric(15, 2) not null,
    vat_amount       numeric(15, 2) not null,
    total            numeric(15, 2) not null,
    version          bigint not null,
    created_at       timestamp not null
);

-- Snapshots : designation, unite et prix sont copies, jamais relies au catalogue vivant.
create table quote_lines (
    id          bigint generated by default as identity primary key,
    quote_id    bigint not null references quotes (id) on delete cascade,
    line_order  integer not null,
    material_id bigint references materials (id),
    designation varchar(255) not null,
    unit_label  varchar(20) not null,
    quantity    numeric(15, 3) not null check (quantity > 0),
    unit_price  numeric(15, 2) not null check (unit_price >= 0),
    line_total  numeric(15, 2) not null
);
create index idx_quote_lines_quote on quote_lines (quote_id);

create table quote_templates (
    id          bigint generated by default as identity primary key,
    name        varchar(150) not null unique,
    description varchar(255)
);

create table quote_template_items (
    id          bigint generated by default as identity primary key,
    template_id bigint not null references quote_templates (id) on delete cascade,
    material_id bigint not null references materials (id),
    quantity    numeric(15, 3) not null check (quantity > 0)
);

